#ifndef MY_MACHINE_H
#define MY_MACHINE_H

#include <stdint.h>
#include <stdbool.h>

// ==============================================================================
// 1. ГЛОБАЛЬНЫЙ ТУМБЛЕР ДВУХЭШЕЛОННОЙ КРИПТОЗАЩИТЫ (ON = 1 / OFF = 0)
// ==============================================================================
#define ENABLE_SECURITY_SUBSYSTEM   1  // 1 - Защита активна, 0 - Режим чистой отладки

// ==============================================================================
// 2. КИНЕМАТИКА И БАЗОВАЯ ТОПОЛОГИЯ ОСЕЙ grblHAL
// ==============================================================================
#define N_AXIS                      8
#define AXIS_NAMES                  "XYZUVR1R2" // X,Y - Портал, Z1..Z4(U,V) - Ход сопел, R1,R2 - Вращение

// Настройки тактовой частоты Hard Real-Time планировщика
#define CNC_TICK_FREQ_HZ            2000       // Частота квантования траектории (2 кГц)
#define CNC_TICK_PERIOD_US          500        // Квант времени (0.5 мс)

// ==============================================================================
// 3. МЕЖПРОЦЕССОРНЫЙ МОСТ СВЯЗИ (SPI2 DMA)
// ==============================================================================
#define SPI_BRIDGE_PACKET_SIZE      48         // Сжатый размер пакета (кратен 32 байтам для кэша MPU)
#define SPI_BRIDGE_TIMEOUT_MS       5          // Таймаут ожидания транзакции

// Аппаратные пины линии синхронизации и E-Stop READY
#define READY_PORT                  GPIOD
#define READY_PIN                   GPIO_PIN_3 // PD3 - Вход EXTI прерывания по спаду уровня

// ==============================================================================
// 4. ПРОМЫШЛЕННЫЙ MPG ПУЛЬТ (ИНТЕРФЕЙС RJ45)
// ==============================================================================
// Аппаратный маховик (Энкодер TIM1 на портах PE9/PE11 через uA9639)
#define TIM_MPG_ENCODER             TIM1
#define MPG_ENCODER_FILTER_TICKS    12         // Встроенный цифровой фильтр таймера от дребезга

// Сетка порогов АЦП для галетного переключателя выбора осей (AXIS_ADC на пине PA4)
// Расчет для делителя 5.1к / 10к при питании ОУ пульта MCP6002 от 5В
#define MPG_AXIS_ADC_VAL_OFF        4095       // Кнопки отпущены / Переключатель в Off (3.3В на пине)
#define MPG_AXIS_ADC_VAL_X          718        // Положение X (~0.57В на пине)
#define MPG_AXIS_ADC_VAL_Y          1300       // Положение Y (~1.05В на пине)
#define MPG_AXIS_ADC_VAL_Z          2048       // Положение Z (~1.65В на пине)
#define MPG_AXIS_ADC_VAL_C          2780       // Положение C (~2.24В на пине)
#define MPG_ADC_TOLERANCE           120        // Аппаратный допуск/окно погрешности кодов АЦП (+/-)

// Сетка порогов АЦП для галетного переключателя множителя (SCALE_ADC на пине PA5)
#define MPG_SCALE_ADC_VAL_X1        718        // Шаг х1 (Микроны)
#define MPG_SCALE_ADC_VAL_X10       1300       // Шаг х10
#define MPG_SCALE_ADC_VAL_X100      2048       // Шаг х100
#define MPG_DEADMAN_BUTTON_MASK     0x0800     // Бит активации кнопки разрешения (Deadman)

// ==============================================================================
// 5. МАГИСТРАЛЬ УМНЫХ ФИДЕРОВ (ИЗОЛИРОВАННЫЙ RS-485 USART2)
// ==============================================================================
#define RS485_PORT                  GPIOD
#define RS485_TX_PIN                GPIO_PIN_5 // PD5
#define RS485_RX_PIN                GPIO_PIN_6 // PD6
#define RS485_DE_PIN                GPIO_PIN_4 // PD4 - Управление направлением (Driver Enable)
#define RS485_BAUDRATE              115200     // Скорость шины Modbus RTU фидеров

// ==============================================================================
// 6. АНТИКОНТРАФАКТ И РЕЗЕРВ МАСШТАБИРОВАНИЯ ГОЛОВКИ (СВЫШЕ 8 ОСЕЙ)
// ==============================================================================
// Адресация внешней энергонезависимой памяти EEPROM 24LC16B (I2C1: PB6/PB7)
#define EEPROM_I2C_BUS              hi2c1
#define EEPROM_DEVICE_ADDR          (0x50 << 1) // Базовый I2C адрес (Блок 0)
#define EEPROM_WP_PORT              GPIOB
#define EEPROM_WP_PIN               GPIO_PIN_5  // PB5 - Управление аппаратной защитой записи WP

// Адреса скрытых крипто-ячеек в EEPROM
#define SEC_COUNTERFEIT_FLAG_ADDR   0x0F00      // 0x00 - Оригинал, 0x01 - Обнаружен пиратский клон
#define SEC_STARTUP_COUNT_ADDR      0x0F04      // Счетчик оставшихся безопасных включений (Отсрочка)
#define SEC_DELAY_STARTUPS_LIMIT    50          // Количество разрешенных запусков до активации "Карусели"
#define SEC_CHECK_PERIOD_STARTUPS   40          // Частота проведения глубокой аналоговой проверки

// Опорные константы нелинейного RLC отклика для верификации (ЦАП PA4 -> АЦП PA5)
#define SEC_DAC_CHANNEL             DAC_CHANNEL_1
#define SEC_ADC_CHANNEL             ADC_CHANNEL_19
#define SEC_EXPECTED_ADC_MIN        1700        // Минимальный код отклика оригинального контура B1
#define SEC_EXPECTED_ADC_MAX        1820        // Максимальный код отклика оригинального контура B1

// Переменные резерва виртуальной интерполяции (для софт-генератора осей R свыше 8 осей)
#define VIRT_AXIS_MAX_COUNT         8
#define R_STEPS_PER_DEGREE          8.8888f     // Перевод угловых градусов в шаги (1/16 шага)
#define R_MAX_VELOCITY_DEG_SEC      500.0f      // Ограничение софт-скорости виртуального вращения
#define R_MAX_ACCEL_DEG_SEC2        5000.0f     // Ограничение софт-ускорения виртуального вращения

#endif // MY_MACHINE_H


